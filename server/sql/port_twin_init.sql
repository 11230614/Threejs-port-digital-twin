-- 港口数字孪生 PostgreSQL 初始化脚本
-- 用法：先在 Navicat 中创建并连接目标数据库（例如 port_twin），
-- 再执行本文件。CREATE DATABASE 不能放在事务中，按需单独执行：
-- CREATE DATABASE port_twin;

BEGIN;

-- 当前场景的静态设备档案。运行遥测、位置和任务进度不存放在此表。
CREATE TABLE IF NOT EXISTS devices (
    id          VARCHAR(64)  PRIMARY KEY,
    entity_id   VARCHAR(64)  NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL,
    type        VARCHAR(32)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT devices_type_check CHECK (type IN ('agv')),
    CONSTRAINT devices_id_not_blank CHECK (length(btrim(id)) > 0),
    CONSTRAINT devices_entity_id_not_blank CHECK (length(btrim(entity_id)) > 0)
);

-- 集装箱档案。database_id 是数据库数据 ID，business_id 是场景业务箱号（如 C00001）。
-- 静态实例没有独立 ECS 实体，entity_id 允许为空；被提升为动态实体时再写入。
CREATE TABLE IF NOT EXISTS containers (
    database_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id VARCHAR(64) NOT NULL UNIQUE,
    entity_id   VARCHAR(128) UNIQUE,
    asset_id    VARCHAR(64) NOT NULL,
    block_id    VARCHAR(64) NOT NULL,
    area        VARCHAR(128) NOT NULL,
    slot        JSONB NOT NULL DEFAULT '{}'::jsonb,
    state       VARCHAR(32) NOT NULL DEFAULT 'YARD',
    location    VARCHAR(128),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT containers_slot_object_check CHECK (jsonb_typeof(slot) = 'object'),
    CONSTRAINT containers_state_check CHECK (state IN ('YARD', 'RELEASED', 'TRANSPORTING', 'DELIVERED'))
);

INSERT INTO devices (id, entity_id, name, type) VALUES
    ('AGV-01', 'AGV_01', 'AGV 01', 'agv'),
    ('AGV-02', 'AGV_02', 'AGV 02', 'agv'),
    ('AGV-03', 'AGV_03', 'AGV 03', 'agv'),
    ('AGV-04', 'AGV_04', 'AGV 04', 'agv'),
    ('AGV-05', 'AGV_05', 'AGV 05', 'agv')
ON CONFLICT (id) DO UPDATE SET
    entity_id = EXCLUDED.entity_id,
    name = EXCLUDED.name,
    type = EXCLUDED.type;

-- 任务记录。parameters/failure 使用 JSONB，以保留现有 API 的对象结构。
CREATE TABLE IF NOT EXISTS tasks (
    id                VARCHAR(96)  PRIMARY KEY,
    client_request_id VARCHAR(100) NOT NULL UNIQUE,
    type              VARCHAR(32)  NOT NULL,
    parameters        JSONB        NOT NULL DEFAULT '{}'::jsonb,
    status            VARCHAR(16)  NOT NULL DEFAULT 'pending',
    stage             VARCHAR(64)  NOT NULL DEFAULT 'created',
    agv_id            VARCHAR(64),
    agv_entity_id     VARCHAR(64),
    container_id      VARCHAR(64),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    failure           JSONB,
    CONSTRAINT tasks_type_check CHECK (type IN (
        'TRANSPORT_CONTAINER', 'TRANSPORT', 'LOADING', 'DISCHARGE',
        'YARD_TRANSFER', 'CHARGING'
    )),
    CONSTRAINT tasks_status_check CHECK (status IN ('pending', 'running', 'completed', 'failed')),
    CONSTRAINT tasks_parameters_object_check CHECK (jsonb_typeof(parameters) = 'object'),
    CONSTRAINT tasks_failure_object_check CHECK (failure IS NULL OR jsonb_typeof(failure) = 'object'),
    CONSTRAINT tasks_agv_fk FOREIGN KEY (agv_id) REFERENCES devices (id),
    CONSTRAINT tasks_agv_entity_fk FOREIGN KEY (agv_entity_id) REFERENCES devices (entity_id),
    CONSTRAINT tasks_container_fk FOREIGN KEY (container_id) REFERENCES containers (business_id)
);

-- 兼容已创建过的旧 tasks 表；重复执行安全。
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS container_id VARCHAR(64);
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'tasks_container_fk'
    ) THEN
        ALTER TABLE tasks ADD CONSTRAINT tasks_container_fk
            FOREIGN KEY (container_id) REFERENCES containers (business_id);
    END IF;
END;
$$;

-- 每个任务的执行事件按 event_id 去重，并保证 sequence 不重复。
CREATE TABLE IF NOT EXISTS task_execution_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id     VARCHAR(96) NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    event_id    VARCHAR(128) NOT NULL,
    sequence    INTEGER      NOT NULL,
    status      VARCHAR(16)  NOT NULL,
    stage       VARCHAR(64),
    agv_id      VARCHAR(64),
    agv_entity_id VARCHAR(64),
    failure     JSONB,
    payload     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT task_events_event_unique UNIQUE (task_id, event_id),
    CONSTRAINT task_events_sequence_unique UNIQUE (task_id, sequence),
    CONSTRAINT task_events_sequence_check CHECK (sequence >= 1),
    CONSTRAINT task_events_status_check CHECK (status IN ('running', 'completed', 'failed')),
    CONSTRAINT task_events_failure_object_check CHECK (failure IS NULL OR jsonb_typeof(failure) = 'object'),
    CONSTRAINT task_events_payload_object_check CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT task_events_agv_fk FOREIGN KEY (agv_id) REFERENCES devices (id),
    CONSTRAINT task_events_agv_entity_fk FOREIGN KEY (agv_entity_id) REFERENCES devices (entity_id)
);

-- 最新一条真实设备遥测。没有上报记录时表示“未知”，不能推断为离线。
-- 本阶段不插入模拟遥测；只有接入真实设备/网关后才写入此表。
CREATE TABLE IF NOT EXISTS device_telemetry (
    device_id       VARCHAR(64) PRIMARY KEY REFERENCES devices (id) ON DELETE CASCADE,
    online_status   VARCHAR(16),
    position        JSONB,
    speed           DOUBLE PRECISION,
    battery         DOUBLE PRECISION,
    payload         JSONB NOT NULL DEFAULT '{}'::jsonb,
    observed_at     TIMESTAMPTZ NOT NULL,
    received_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT device_telemetry_online_status_check
        CHECK (online_status IS NULL OR online_status IN ('online', 'offline')),
    CONSTRAINT device_telemetry_position_object_check
        CHECK (position IS NULL OR jsonb_typeof(position) = 'object'),
    CONSTRAINT device_telemetry_payload_object_check
        CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT device_telemetry_speed_nonnegative_check
        CHECK (speed IS NULL OR speed >= 0),
    CONSTRAINT device_telemetry_battery_range_check
        CHECK (battery IS NULL OR (battery >= 0 AND battery <= 100))
);

-- 告警记录可关联 AGV 等设备，也可关联道路、岸桥等场景资产；
-- entity_type/entity_id 保留通用资产映射，不为场景中的非设备强加 devices 外键。
-- 本阶段不从随机遥测生成或写入告警。
CREATE TABLE IF NOT EXISTS alarms (
    id              VARCHAR(160) PRIMARY KEY,
    type            VARCHAR(64) NOT NULL,
    severity        VARCHAR(16) NOT NULL,
    status          VARCHAR(16) NOT NULL DEFAULT 'active',
    entity_type     VARCHAR(32) NOT NULL,
    entity_id       VARCHAR(64) NOT NULL,
    device_id       VARCHAR(64) REFERENCES devices (id) ON DELETE SET NULL,
    message         TEXT NOT NULL,
    suggestion      TEXT,
    details         JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT alarms_severity_check CHECK (severity IN ('info', 'warning', 'severe', 'urgent')),
    CONSTRAINT alarms_status_check CHECK (status IN ('active', 'acknowledged', 'dispatched', 'closed')),
    CONSTRAINT alarms_details_object_check CHECK (jsonb_typeof(details) = 'object')
);

CREATE INDEX IF NOT EXISTS idx_tasks_status_created ON tasks (status, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_tasks_type_created ON tasks (type, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_containers_block_state ON containers (block_id, state, business_id);
CREATE INDEX IF NOT EXISTS idx_task_events_task_sequence ON task_execution_events (task_id, sequence);
CREATE INDEX IF NOT EXISTS idx_device_telemetry_observed_at ON device_telemetry (observed_at DESC);
CREATE INDEX IF NOT EXISTS idx_alarms_status_occurred_at ON alarms (status, occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_alarms_entity ON alarms (entity_type, entity_id, occurred_at DESC);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS tasks_set_updated_at ON tasks;
CREATE TRIGGER tasks_set_updated_at
BEFORE UPDATE ON tasks
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE devices IS '当前场景静态设备档案；AGV-01..AGV-05 为演示清单';
COMMENT ON TABLE tasks IS '运输任务记录；状态转换仍由应用层按执行事件校验';
COMMENT ON TABLE task_execution_events IS '前端执行器回报的幂等事件流水';
COMMENT ON TABLE device_telemetry IS '设备最新遥测快照；空表表示尚无真实遥测数据，不能据此判定设备离线';
COMMENT ON TABLE alarms IS '设备与场景资产告警；由接入真实数据后的告警规则写入，本脚本不生成模拟告警';
COMMENT ON COLUMN tasks.client_request_id IS '创建请求幂等键，替代内存 clientRequests Map';

COMMIT;
