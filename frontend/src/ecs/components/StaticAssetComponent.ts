// ============================================================================
// StaticAssetComponent.js —— 静态资产组件（Static Asset：不会动的布景物件）
//
// 【这个文件干什么】
// 给“永远不动”的模型贴标签，例如厂房、堆场地面、灯塔、围墙。
// 打上这个标记后，运动系统（MotionSystem）会跳过它们不做位移计算，
// 渲染优化也可以把它们合并成一批（batch，批次）来减少绘制开销。
//
// 【术语翻译】
//   Static（静态的、不动的）   Asset（资产，此处指场景中的模型物件）
//   value（值）   default parameter（默认参数）
// ============================================================================

export class StaticAssetComponent {
  constructor(public value = true) {}
}
